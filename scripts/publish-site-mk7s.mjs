#!/usr/bin/env node
// Build the holofx site under /holofx/ and stage it in mk7s's Cloudflare Pages site.
//
//   node scripts/publish-site-mk7s.mjs                build + copy into ../../mk7s/public/holofx
//   node scripts/publish-site-mk7s.mjs --skip-build   copy the existing site/dist (built with SITE_BASE=/holofx/)
//   node scripts/publish-site-mk7s.mjs --deploy       ...then build mk7s and deploy it with Wrangler
//
// Options: --mk7s <path> (default ../../mk7s), --branch <name> (default main, the production branch).
// Every project must have its dependencies installed first (`npm run bootstrap`).
import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { parseArgs } from 'node:util';

const BASE = '/holofx';
const { values } = parseArgs({
  options: {
    mk7s: { type: 'string' },
    deploy: { type: 'boolean', default: false },
    'skip-build': { type: 'boolean', default: false },
    branch: { type: 'string', default: 'main' },
  },
});
const root = path.resolve(import.meta.dirname, '..');
const mk7s = path.resolve(root, values.mk7s ?? '../../mk7s');
const source = path.join(root, 'site/dist');
const target = path.join(mk7s, `public${BASE}`);
if (
  !existsSync(path.join(mk7s, 'package.json')) ||
  JSON.parse(readFileSync(path.join(mk7s, 'package.json'), 'utf8')).name !== 'mk7s'
) {
  throw new Error(`Expected the mk7s site at ${mk7s}`);
}

function run(command, args, cwd, env = {}) {
  const result = spawnSync(command, args, { cwd, stdio: 'inherit', env: { ...process.env, ...env } });
  if (result.status !== 0) throw new Error(`${command} ${args.join(' ')} failed with status ${result.status}`);
}

// The same build GitHub Pages runs: libraries, labs, catalogue and site, all under the prefix.
if (!values['skip-build']) run('npm', ['run', 'build'], root, { SITE_BASE: `${BASE}/` });

// A build without the prefix would load its scripts and styles from mk7s's root; refuse it.
const index = readFileSync(path.join(source, 'index.html'), 'utf8');
if (!index.includes(`src="${BASE}/`) && !index.includes(`href="${BASE}/_astro/`)) {
  throw new Error(`site/dist was not built with SITE_BASE=${BASE}/; drop --skip-build`);
}
for (const lab of ['hologpu', 'firetemple', 'watertemple', 'lighttemple', 'eightfoldpath']) {
  if (!existsSync(path.join(source, 'labs', lab, 'index.html'))) throw new Error(`Build is missing labs/${lab}`);
}
// The build's file names are hashed, so replace the staged copy rather than adding to it.
mkdirSync(path.dirname(target), { recursive: true });
rmSync(target, { recursive: true, force: true });
cpSync(source, target, { recursive: true });

const headersPath = path.join(mk7s, 'public/_headers');
const begin = '# BEGIN holofx (generated by holofx/scripts/publish-site-mk7s.mjs)';
const end = '# END holofx';
let headers = existsSync(headersPath) ? readFileSync(headersPath, 'utf8') : '';
const first = headers.indexOf(begin);
const last = headers.indexOf(end);
if (first >= 0 && last > first) headers = headers.slice(0, first) + headers.slice(last + end.length);
const block = `${begin}\n${BASE}/*\n  Cache-Control: public, max-age=0, must-revalidate\n  X-Content-Type-Options: nosniff\n${BASE}/_astro/*\n  ! Cache-Control\n  Cache-Control: public, max-age=31536000, immutable\n${end}`;
writeFileSync(headersPath, `${headers.trim()}\n\n${block}\n`);

const redirectsPath = path.join(mk7s, 'public/_redirects');
const redirects = existsSync(redirectsPath) ? readFileSync(redirectsPath, 'utf8') : '';
const redirect = `${BASE} ${BASE}/ 308`;
if (!redirects.split('\n').includes(redirect)) writeFileSync(redirectsPath, `${redirects.trimEnd()}\n${redirect}\n`);

console.log(`Staged ${target}`);
if (values.deploy) {
  run('npm', ['run', 'build'], mk7s);
  run('npx', ['wrangler', 'pages', 'deploy', 'dist', '--project-name', 'mk7s', '--branch', values.branch], mk7s);
}
